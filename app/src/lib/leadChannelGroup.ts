/**
 * 유입경로 묶기.
 *
 * 유입경로 칸에 개별 행사명과 콘텐츠명이 그대로 들어가 있다. 웨비나가 11가지
 * 이름으로, SNS 가 65가지로 흩어져서 "웨비나 성공률" 을 볼 수가 없었다.
 * 표기 흔들림도 많다 — Instagram / 인스타그램 / 인스타 / 인스타구램.
 *
 * 원본(source_channel)은 건드리지 않고 화면에서만 묶는다. 그래야 행사별 상세를
 * 잃지 않고, 묶는 기준이 틀렸을 때 되돌리기도 쉽다.
 */

export const CHANNEL_GROUPS = [
  '웨비나/세미나',
  'SNS',
  '홈페이지 문의',
  '외부소개',
  '카카오톡',
  '기존 학생',
  '미입력',
  '기타',
] as const

export type ChannelGroup = (typeof CHANNEL_GROUPS)[number]

/**
 * 한 유입경로 이름이 어느 묶음인지.
 *
 * 순서가 중요하다. '세미나 - EC&BIO 웨비나' 처럼 두 낱말이 같이 들어간 이름이
 * 있어서, 먼저 걸리는 규칙이 이긴다.
 */
export function channelGroupOf(raw?: string): ChannelGroup {
  const n = (raw || '').trim()
  // 빈 값은 집계 전에 '미입력' 이라는 이름으로 바뀌어 들어온다. 그 글자 자체를
  // 여기서 알아보지 못하면 어느 규칙에도 안 걸려 '기타' 로 떨어진다 — 실제로
  // 유입경로가 빈 리드 3건이 기타에 섞여 있었다.
  if (!n || n === '미입력' || n === '(미입력)') return '미입력'

  if (/홈페이지/.test(n)) return '홈페이지 문의'
  if (/카카오/.test(n)) return '카카오톡'

  // 리드 없이 바로 계약된 건. '추천' 한 낱말로 잡으면 '추천 리스트'·'추천서'
  // 같은 행사·콘텐츠 제목까지 빨려 들어간다 — 실제로 29건이 그렇게 샜다.
  // 그래서 통째로 같은 이름만 본다.
  if (/^(외부소개|소개\/추천|국민이주 소개|지인|대표 직접|대표직접)$/.test(n)) return '외부소개'
  if (/^(재계약|기존 서비스 학생|기존학생)$/.test(n)) return '기존 학생'

  // 행사: 웨비나·세미나·워크샵을 하나로. 온라인/오프라인을 갈라 봐야
  // '행사를 열어 모은 리드' 라는 점은 같다.
  if (/웨비나|세미나|워크샵|워크숍|GIA/i.test(n)) return '웨비나/세미나'

  // SNS·광고: 'SNS - ' 접두사, 인스타 표기 변형(인스타그램·인스타·인스타구램), 유튜브, 광고
  if (/^sns\b|^sns\s*-|인스타|instagram|유투브|유튜브|youtube|광고/i.test(n)) return 'SNS'

  // 행사 신청 폼의 제목이 그대로 들어온 것들. 키워드가 없어도 '이모지로 시작'
  // 하거나 '— / · 가 든 긴 제목' 이면 행사 제목으로 본다.
  // (예: '🗺️ 학년별 로드맵 구축 전략 — 9학년부터 11학년까지')
  if (n.length >= 15 && (/[—·]/.test(n) || /^[^\p{L}\p{N}\s]/u.test(n))) return '웨비나/세미나'

  return '기타'
}
