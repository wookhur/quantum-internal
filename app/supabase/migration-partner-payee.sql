-- ============================================================
-- 수령인 지정 — 일한 사람과 받는 사람이 다를 때
-- ------------------------------------------------------------
-- 이준형님의 관리비를 이상민님 이름으로 청구·수령하는 것처럼, 청구 대상과 실제
-- 수령인이 다른 경우가 있다.
--
-- 지급 원장은 수령인 이름으로 적힌다. 그래서 이상민님께 지급해도 이준형님의 청구
-- 목록은 미지급으로 남고, 지급이 끝난 달이 다음 달에도 계속 올라왔다.
--
-- 여기에 수령인을 적어 두면 두 가지가 맞춰진다:
--   · 발행할 때 수령인 칸이 그 이름으로 미리 채워진다 (손으로 고쳐 쓰다 생기는 혼선 차단)
--   · 그 이름으로 지급된 건이 청구 대상의 목록을 내려 준다
--
-- 비워 두면 본인이 받는 것으로 본다.
-- Safe to re-run.
-- ============================================================

alter table public.partner_invoice_types
  add column if not exists payee_name text;

comment on column public.partner_invoice_types.payee_name is
  '돈을 실제로 받는 사람 이름. 청구 대상과 다를 때만 적는다(비우면 본인). 지급 원장 매칭에 쓰인다.';

notify pgrst, 'reload schema';
